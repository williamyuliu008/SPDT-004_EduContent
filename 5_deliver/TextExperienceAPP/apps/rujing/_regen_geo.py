# Build 32 cards
cards = []
card_id = 1

for chain in all_chains:
    cid = chain['chain_id']
    chain_name = chain['chain_name']  # full name e.g. "黄河·九曲入海"
    chain_tags = chain.get('chain_tags', [])
    content = CHAIN_CONTENT.get(cid, {})

    # Clean tags: remove any with length > 15
    clean_tags = [t for t in chain_tags if isinstance(t, str) and len(t) <= 15]
    if not clean_tags:
        clean_tags = [cid.split('_')[-1]]  # fallback

    # Node card
    node_card = {
        'card_id': f'GEO_NAT_{card_id:03d}',
        'chain_id': cid,
        'chain_title': chain_name,
        'card_type': 'node',
        'chain_role': 'pivot',
        'front': content.get('node_front', f'{chain_name}的知识要点是什么？'),
        'back_core': content.get('node_back', chain.get('causal_logic', '')),
        'back_detail': content.get('node_detail', ''),
        'tags': clean_tags[:4],
    }
    cards.append(node_card)
    card_id += 1

    # Strategy card
    strategy_card = {
        'card_id': f'GEO_NAT_{card_id:03d}',
        'chain_id': cid,
        'chain_title': chain_name,
        'card_type': 'strategy',
        'chain_role': 'result',
        'front': content.get('strat_front', f'{chain_name}的实践启示是什么？'),
        'back_core': content.get('strat_back', ''),
        'back_detail': content.get('strat_detail', ''),
        'tags': clean_tags[4:8] if len(clean_tags) > 4 else clean_tags[:4],
    }
    cards.append(strategy_card)
    card_id += 1

# Build package
package = {
    'package_id': 'GEO_SHANHE_SERIES',
    'package_title': '地理山河系列',
    'schema_version': 'v3',
    'node_cards': cards,
    'total_cards': len(cards),
    'total_chains': 16,
}

# Validate
try:
    json_str = json.dumps(package, ensure_ascii=False, indent=2)
    # Check for any remaining control characters
    for i, c in enumerate(json_str):
        code = ord(c)
        if code < 32 and c not in '\n\t':
            print(f'WARNING: Control char 0x{code:02X} at pos {i}')
    obj = json.loads(json_str)
    print(f'Valid JSON! {len(obj["node_cards"])} cards, {obj["total_chains"]} chains')
    for c in obj['node_cards'][:4]:
        print(f'  [{c["card_id"]}] chain={c["chain_title"]} front={c["front"][:20]}...')
except Exception as e:
    print(f'Error: {e}')
    sys.exit(1)

