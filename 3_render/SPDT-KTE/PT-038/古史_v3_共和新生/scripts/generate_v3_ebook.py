class ModernHistoryMD:
    """输出 Markdown 版电子书"""

    def __init__(self, episodes):
        self.episodes = episodes

    def render(self):
        lines = []
        lines += self._header()
        for ep in self.episodes:
            lines += self._ep(ep)
        return "\n".join(lines)

    def _header(self):
        return [
            "# 共和新生",
            "## 1840-1949：从天朝崩塌到人民共和国",
            "",
            "**卷三 · 中国近现代史**",
            "",
            "---\n",
            "",
            "## 内容概要",
            "",
            "| 集 | 标题 | 时间跨度 | 核心问题 | 知识链 | 高频点 | 核心概念 |",
            "|---|---|---|---|---|---|---|",
            "| Ep01 | 天朝崩塌 | 1840-1864 | 洋务运动能否救亡？ | 4条 | 8个 | 5个 |",
            "| Ep02 | 帝国挽歌 | 1864-1912 | 制度变革为何艰难？ | 4条 | 8个 | 5个 |",
            "| Ep03 | 觉醒年代 | 1912-1935 | 新道路在哪里？ | 4条 | 9个 | 4个 |",
            "| Ep04 | 共和新生 | 1931-1949 | 新中国为何必然？ | 4条 | 9个 | 5个 |",
            "",
            "**时间线总览**：1840年鸦片战争 → 1912年清帝退位 → 1949年新中国成立",
            "**109年苦难辉煌 · 完整覆盖高考中国近现代史全部高频考点**",
            "",
            "---\n",
        ]

    def _ep(self, ep):
        lines = []
        ep_num = ep["ep"]
        lines.append(f"\n# 第{ep_num}集 · {ep['title']}")
        lines.append(f"## {ep['subtitle']}")
        lines.append(f"**时间跨度**：{ep['time_period']}（{ep['duration']}）\n")

        # ── 第一幕：时间线 ────────────────────────────────────
        lines.append("## 第一幕 · 时间线\n")
        tl = ep["timeline"]
        lines.append(f"**总述**：{tl['overview'].strip()}\n")
        lines.append("| 年代 | 事件 | 描述 | 意义 |")
        lines.append("|---|---|---|---|")
        for ev in tl["events"]:
            lines.append(
                f"| {ev['year']} | **{ev['title']}** | {ev['description'][:80]}…… | {ev['significance']} |"
            )
        lines.append("")

        # ── 第二幕：艺术问题 ────────────────────────────────────
        aq = ep["art_question"]
        lines.append("## 第二幕 · 艺术问题\n")
        lines.append(f"**设问**：{aq['question']}\n")
        lines.append(f"{aq['context'].strip()}\n")
        lines.append(f"> **洞察**：{aq['insight'].strip()}\n")

        # ── 第三幕：当代回响 ────────────────────────────────────
        ce = ep["contemporary_echo"]
        lines.append("## 第三幕 · 当代回响\n")
        lines.append(f"**总述**：{ce['overview'].strip()}\n")
        for i, pt in enumerate(ce["echo_points"], 1):
            lines.append(f"### {i}. {pt['modern_issue']}")
            lines.append(f"**历史关联**：{pt['historical_connection']}")
            lines.append(f"**当代启示**：{pt['contemporary_reflection']}\n")

        # ── 第四幕：春秋笔法 ────────────────────────────────────
        sat = ep["spring_autumn_transition"]
        lines.append("## 第四幕 · 春秋笔法\n")
        if sat.get("from_this_volume_ep1"):
            prev = sat["from_this_volume_ep1"]
            lines.append(f"**上接**：{prev['preceding_ep']}")
            lines.append(f"{prev['transition_sentence'].strip()}\n")
        if sat.get("to_ep2"):
            nxt = sat["to_ep2"]
            lines.append(f"**下承**：{nxt['next_ep']} — {nxt['forward_context'].strip()}\n")
        if sat.get("to_modern_history") and sat["to_modern_history"].get("series_conclusion"):
            sc = sat["to_modern_history"]["conclusion_context"]
            lines.append(f"### 全系列结语\n{sc.strip()}\n")

        # ── 附录：知识链 ────────────────────────────────────────
        chains = ep["knowledge_chains"]
        lines.append("## 附录 · 知识链\n")
        for ch_id, ch in chains.items():
            lines.append(f"### {ch['chain_id']}：{ch['chain_title']}")
            lines.append(f"**类型**：{ch['chain_type']}")
            lines.append(f"**核心规律**：{ch['core_pattern']}\n")
            lines.append(f"{ch['narrative'].strip()}\n")
            lines.append("**关键节点**：")
            for nd in ch["key_nodes"]:
                lines.append(f"- {nd['node']} → {nd['answer']}")
            lines.append("")

        # ── 高频考点 ───────────────────────────────────────────
        lines.append("### 高频考点速记\n")
        for pt in ep["high_frequency_points"]:
            lines.append(f"- {pt}")
        lines.append("")

        # ── 核心概念 ───────────────────────────────────────────
        lines.append("### 核心概念\n")
        for cpt in ep["key_concepts"]:
            lines.append(f"**{cpt['concept']}**：{cpt['definition'].strip()}")
            lines.append(f"*{cpt['exam_tip']}*\n")

        lines.append("\n---\n")
        return lines

    def save(self, out_path):
        content = self.render()
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(content)
        size = os.path.getsize(out_path)
        print(f"[MD] 写入成功：{out_path}（{size/1024:.1f} KB）")


