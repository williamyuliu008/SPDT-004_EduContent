# ── 加载数据文件 ────────────────────────────────────────────
def load_episodes():
    """加载所有四集 Python 数据模块"""
    episodes = []
    script_dir = os.path.dirname(os.path.abspath(__file__))

    episode_files = [
        "古史_v3_ep01_天朝崩塌.py",
        "古史_v3_ep02_帝国挽歌.py",
        "古史_v3_ep03_觉醒年代.py",
        "古史_v3_ep04_共和新生.py",
    ]

    for fname in episode_files:
        fpath = os.path.join(script_dir, fname)
        namespace = {}
        with open(fpath, "r", encoding="utf-8") as f:
            content = f.read()
        exec(compile(content, fpath, "exec"), namespace)
        episodes.append(namespace["get_data"]())

    return episodes


